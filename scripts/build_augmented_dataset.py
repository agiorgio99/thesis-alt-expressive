#!/usr/bin/env python3
"""
build_augmented_dataset.py
──────────────────────────
Build an augmented copy of one GTSinger language tree.

For every  {Singer}/{Technique}/{Song}  directory that contains a Control_Group:
  • Control_Group/         ← symlinked from the original (or --copy)
  • Paired_Speech_Group/   ← symlinked from the original (or --copy, if present)
  • {Technique_Group}/     ← generated by augmenting every Control_Group WAV
                              (3 variants per clip).
                              Output filenames: {orig_stem}_v{k}.wav / .json

Engines (--engine):
  legacy    v1 presets, 16 kHz, whole-clip WORLD (the original behaviour;
            default output data/GTSinger_Augmented/<Lang>)
  world_v2  data-driven, 48 kHz, local resynthesis, every technique
  psola     Praat PSOLA for the pitch techniques (others fall back to world_v2)
  auto      psola for vibrato / glissando, world_v2 for the rest
New engines write float WAVs at the native rate to data/GTSinger_aug_<engine>/<Lang>
plus augment_manifest.csv (engine, group, parameters of every variant). For the
Mixed_Voice_and_Falsetto folder each control clip is turned into the group
(Mixed_Voice or Falsetto) of its paired real take, so the real 50/50 split is
kept and every clip still gets 3 variants.

Parameters of the new engines (--param-mode):
  quartile  q25 / q50 / q75 of the real effect (the pilot presets)
  sampled   per-clip draws from the whole real distribution (default)
  tails     draws pushed toward both tails (--tail-gamma, default 0.6)
--targets language (default) uses the clip's language calibration; pooled
uses all languages together (F0 change per voice type).

Usage
─────
  python scripts/build_augmented_dataset.py                  # v1, English
  python scripts/build_augmented_dataset.py --techniques Vibrato Breathy
  python scripts/build_augmented_dataset.py --dry-run        # preview only
  python scripts/build_augmented_dataset.py --copy           # full copy vs symlink
  python scripts/build_augmented_dataset.py --workers 4      # parallel jobs
  python scripts/build_augmented_dataset.py --language italian --engine auto \
         --param-mode sampled --exclude-test-songs --workers 24
"""

import argparse
import csv
import json
import logging
import os
import shutil
import sys
import traceback
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

import soundfile as sf

try:
    from tqdm import tqdm
except ImportError:
    def tqdm(it, **kw):
        return it

# The transforms live in the alt.augment package (shared with the calibration
# scripts and the Gradio app); this script is the batch CLI around them.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from alt.augment.io import VOWELS_BY_LANGUAGE, load_utterance  # noqa: E402
from alt.augment.legacy import (  # noqa: E402
    SR, TECHNIQUE_CONFIG, world_decompose,
)
from alt.augment.pairing import load_test_songs, song_key  # noqa: E402
from alt.augment.world_core import seed_for  # noqa: E402

REPO = Path(__file__).resolve().parent.parent

# Technique folder → real technique groups it contains (new engines generate
# the group of each clip's paired real take; v1 only knew Falsetto).
FOLDER_GROUPS: dict[str, list[str]] = {
    "Vibrato": ["Vibrato_Group"],
    "Breathy": ["Breathy_Group"],
    "Glissando": ["Glissando_Group"],
    "Pharyngeal": ["Pharyngeal_Group"],
    "Mixed_Voice_and_Falsetto": ["Mixed_Voice_Group", "Falsetto_Group"],
}
# --engine auto: tentative best engine per group (pilot, 2026-09-26).
AUTO_ENGINE: dict[str, str] = {"Vibrato_Group": "psola", "Glissando_Group": "psola"}
TAIL_GAMMA = {"sampled": 1.0, "tails": 0.6}
N_VARIANTS = 3

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)-7s %(message)s",
    datefmt="%H:%M:%S",
)
log = logging.getLogger(__name__)

# ── Per-utterance worker (called in subprocess) ───────────────────────────────

def _process_utterance(args_tuple):
    """
    Process one control WAV → list of (wav_path, json_path) output pairs.
    Returns (n_ok, n_err, list_of_skipped_messages).
    """
    ctrl_wav_str, out_tech_dir_str, cfg_key, dry_run, language = args_tuple
    ctrl_wav      = Path(ctrl_wav_str)
    out_tech_dir  = Path(out_tech_dir_str)
    cfg           = TECHNIQUE_CONFIG[cfg_key]
    params_list   = cfg["params"]
    augment_fn    = cfg["augment_fn"]
    vowels        = VOWELS_BY_LANGUAGE[language]

    ctrl_json = ctrl_wav.with_suffix(".json")
    if not ctrl_json.exists():
        return 0, 0, [f"SKIP (no json): {ctrl_wav}"]

    # Check if all variants already exist (resumable run)
    stem = ctrl_wav.stem
    all_exist = all(
        (out_tech_dir / f"{stem}_v{k}.wav").exists()
        for k in range(len(params_list))
    )
    if all_exist:
        return len(params_list), 0, []

    try:
        wav, meta = load_utterance(ctrl_wav, ctrl_json, sr=SR)
        f0, sp, ap = world_decompose(wav)
    except Exception as e:
        return 0, 1, [f"ERR load {ctrl_wav}: {e}"]

    n_ok, n_err = 0, 0
    msgs = []
    for k, params in enumerate(params_list):
        out_wav  = out_tech_dir / f"{stem}_v{k}.wav"
        out_json = out_tech_dir / f"{stem}_v{k}.json"
        if out_wav.exists():
            n_ok += 1
            continue
        if dry_run:
            msgs.append(f"[DRY] {out_wav}")
            n_ok += 1
            continue
        try:
            wav_aug, meta_aug = augment_fn(f0, sp, ap, meta, params, vowels)
            sf.write(out_wav, wav_aug, SR)
            with open(out_json, "w") as fh:
                json.dump(meta_aug, fh, indent=2)
            n_ok += 1
        except Exception as e:
            n_err += 1
            msgs.append(f"ERR aug {ctrl_wav} v{k}: {e}\n{traceback.format_exc()}")
    return n_ok, n_err, msgs

# ── Per-utterance worker for the data-driven engines ─────────────────────────

def pick_group(ctrl_wav: Path, folder: str) -> str:
    """Technique group to synthesise for one control clip.

    Prefers the group whose real take of the same phrase exists (its flags
    tell the engine where to apply the technique); among several, picks one
    deterministically per clip so the real proportions are kept.

    Args:
        ctrl_wav: Control-take WAV (``.../<Song>/Control_Group/<stem>.wav``).
        folder:   Technique folder name ("Mixed_Voice_and_Falsetto", ...).

    Returns:
        The group name.
    """
    song_dir = ctrl_wav.parent.parent
    groups = FOLDER_GROUPS[folder]
    paired = [g for g in groups if (song_dir / g / f"{ctrl_wav.stem}.json").exists()]
    present = [g for g in groups if (song_dir / g).is_dir()]
    cands = paired or present or groups
    return cands[seed_for(ctrl_wav.stem, song_dir.name) % len(cands)]


def engine_for(group: str, engine: str) -> str:
    """Engine that realises ``group`` (psola cannot do voice quality)."""
    from alt.augment.engines import ENGINES
    eng = AUTO_ENGINE.get(group, "world_v2") if engine == "auto" else engine
    return eng if group in ENGINES[eng].groups else "world_v2"


def variant_params(eng: str, group: str, targets: str, mode: str, gamma: float,
                   clip_key: str) -> list[dict]:
    """The N_VARIANTS parameter dicts of one clip.

    Args:
        eng:      "world_v2" or "psola".
        group:    Target group.
        targets:  Calibration providing the targets (language name or "pooled").
        mode:     "quartile", "sampled" or "tails".
        gamma:    Tail exponent for the sampled modes.
        clip_key: Repo-relative control path (seeds the draws).

    Returns:
        Parameter dicts.
    """
    from alt.augment import psola, world_v2
    from alt.augment.engines import ENGINES
    if mode == "quartile":
        return ENGINES[eng].presets(group, targets)
    mod = psola if eng == "psola" else world_v2
    return mod.sample_presets(group, targets, clip_key, N_VARIANTS, gamma)


def _process_utterance_v2(args_tuple):
    """Augment one control WAV with a data-driven engine.

    Returns ``(n_ok, n_err, messages, manifest_rows)``.
    """
    (ctrl_wav_str, out_song_str, folder, engine, mode, gamma, targets,
     language, dry_run) = args_tuple
    from alt.augment.engines import ENGINES

    ctrl_wav, out_song = Path(ctrl_wav_str), Path(out_song_str)
    ctrl_json = ctrl_wav.with_suffix(".json")
    if not ctrl_json.exists():
        return 0, 0, [f"SKIP (no json): {ctrl_wav}"], []
    group = pick_group(ctrl_wav, folder)
    eng = engine_for(group, engine)
    out_dir = out_song / group
    stem = ctrl_wav.stem
    outs = [out_dir / f"{stem}_v{k}.wav" for k in range(N_VARIANTS)]
    if all(o.exists() for o in outs):
        return N_VARIANTS, 0, [], []
    if dry_run:
        return N_VARIANTS, 0, [f"[DRY] {o} ({eng}, {group})" for o in outs], []

    try:
        clip_key = str(ctrl_wav.resolve().relative_to(REPO.resolve()))
    except ValueError:
        clip_key = str(ctrl_wav)
    n_ok, n_err, msgs, rows = 0, 0, [], []
    try:
        params_list = variant_params(eng, group, targets, mode, gamma, clip_key)
    except Exception as e:
        return 0, N_VARIANTS, [f"ERR params {ctrl_wav}: {e}"], []
    out_dir.mkdir(parents=True, exist_ok=True)
    for k, (params, out_wav) in enumerate(zip(params_list, outs)):
        if out_wav.exists():
            n_ok += 1
            continue
        try:
            res = ENGINES[eng].run(ctrl_wav, ctrl_json, group, params, language)
            # Float WAV at the native rate: no clipping, no requantisation.
            sf.write(out_wav, res.wav, res.sr, subtype="FLOAT")
            with open(out_wav.with_suffix(".json"), "w") as fh:
                json.dump(res.meta, fh, indent=2, ensure_ascii=False)
            rows.append({"out_wav": str(out_wav), "control_wav": clip_key,
                         "language": language, "folder": folder, "group": group,
                         "engine": eng, "param_mode": mode, "targets": targets,
                         "variant": k, "params": json.dumps(res.params, default=float)})
            n_ok += 1
        except Exception as e:
            n_err += 1
            msgs.append(f"ERR aug {ctrl_wav} v{k}: {e}\n{traceback.format_exc()}")
    return n_ok, n_err, msgs, rows


def write_manifest(dst: Path, rows: list[dict]) -> None:
    """Append this run's variants to ``dst/augment_manifest.csv``."""
    if not rows:
        return
    path = dst / "augment_manifest.csv"
    new = not path.exists()
    with open(path, "a", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        if new:
            w.writeheader()
        w.writerows(rows)


# ── Link / copy helper ────────────────────────────────────────────────────────

def _link_or_copy(src: Path, dst: Path, do_copy: bool, dry_run: bool):
    if dst.exists() or dst.is_symlink():
        return
    if dry_run:
        action = "COPY" if do_copy else "LINK"
        log.info("[DRY] %s %s → %s", action, src, dst)
        return
    if do_copy:
        shutil.copytree(src, dst)
    else:
        dst.symlink_to(src.resolve())

# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--src", default=None,
        help="Original GTSinger language directory "
             "(default: data/GTSinger/<Language>)",
    )
    parser.add_argument(
        "--dst", default=None,
        help="Output directory (default: data/GTSinger_Augmented/<Language> for "
             "legacy, data/GTSinger_aug_<engine>/<Language> otherwise)",
    )
    parser.add_argument(
        "--engine", default="legacy", choices=["legacy", "world_v2", "psola", "auto"],
        help="Augmentation engine (default: legacy = v1 presets)",
    )
    parser.add_argument(
        "--param-mode", default="sampled", choices=["quartile", "sampled", "tails"],
        help="How the data-driven engines choose their 3 variants (default: sampled)",
    )
    parser.add_argument(
        "--tail-gamma", type=float, default=None,
        help="Tail exponent for --param-mode tails (default 0.6; < 1 = more tails)",
    )
    parser.add_argument(
        "--targets", default="language", choices=["language", "pooled"],
        help="Calibration the targets come from: the clip's language (default) "
             "or all languages pooled",
    )
    parser.add_argument(
        "--language", default="english", choices=list(VOWELS_BY_LANGUAGE.keys()),
        help="Dataset language — selects the vowel-phone set used by the "
             "vibrato/glissando transforms to find sung vowels (default: english). "
             "Must match --src's actual language.",
    )
    parser.add_argument(
        "--techniques", nargs="+", default=list(TECHNIQUE_CONFIG.keys()),
        choices=list(TECHNIQUE_CONFIG.keys()),
        metavar="TECHNIQUE",
        help="Which techniques to augment (default: all). "
             f"Choices: {list(TECHNIQUE_CONFIG.keys())}",
    )
    parser.add_argument(
        "--exclude-test-songs", action="store_true",
        help="Skip songs of the language's song-disjoint test split "
             "(results/splits/test_manifest_<iso>.songs.json) so that no "
             "augmented clip is ever derived from held-out lyrics. Saves ~30%% "
             "of the work; finetune_whisper.py filters them out anyway.",
    )
    parser.add_argument(
        "--copy", action="store_true",
        help="Copy Control_Group / Paired_Speech_Group instead of symlinking",
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Print what would be done without writing any files",
    )
    parser.add_argument(
        "--workers", type=int, default=1,
        help="Parallel worker processes (default: 1). "
             "Use 4+ on multi-core machines for ~4× speedup.",
    )
    args = parser.parse_args()

    repo = REPO
    lang_dir = args.language.capitalize()
    if args.src is None:
        args.src = f"data/GTSinger/{lang_dir}"
    if args.dst is None:
        args.dst = (f"data/GTSinger_Augmented/{lang_dir}" if args.engine == "legacy"
                    else f"data/GTSinger_aug_{args.engine}/{lang_dir}")
    src  = (repo / args.src) if not Path(args.src).is_absolute() else Path(args.src)
    dst  = (repo / args.dst) if not Path(args.dst).is_absolute() else Path(args.dst)
    legacy = args.engine == "legacy"
    gamma = args.tail_gamma if args.tail_gamma is not None else \
        TAIL_GAMMA.get(args.param_mode, 1.0)
    targets = "pooled" if args.targets == "pooled" else args.language

    if not src.exists():
        log.error("Source directory not found: %s", src)
        sys.exit(1)

    log.info("Source : %s", src)
    log.info("Output : %s", dst)
    log.info("Techniques : %s", args.techniques)
    if legacy:
        log.info("Engine     : legacy (v1 presets)")
    else:
        log.info("Engine     : %s · params %s (γ=%.2f) · targets %s",
                 args.engine, args.param_mode, gamma, targets)
    log.info("Workers    : %d", args.workers)
    if args.dry_run:
        log.info("DRY RUN — no files will be written")

    test_songs: set[str] = set()
    if args.exclude_test_songs:
        test_songs = load_test_songs(args.language, repo)
        log.info("Excluding %d test songs", len(test_songs))

    # ── Collect tasks ─────────────────────────────────────────────────────────
    # Each task = (ctrl_wav_path, out_tech_dir, technique_name, dry_run)
    tasks = []

    for singer_dir in sorted(src.iterdir()):
        if not singer_dir.is_dir():
            continue
        for tech_dir in sorted(singer_dir.iterdir()):
            if not tech_dir.is_dir():
                continue
            if tech_dir.name not in args.techniques:
                continue
            cfg = TECHNIQUE_CONFIG[tech_dir.name]

            for song_dir in sorted(tech_dir.iterdir()):
                if not song_dir.is_dir():
                    continue
                ctrl_dir = song_dir / "Control_Group"
                if not ctrl_dir.exists():
                    continue
                # song_key() looks two levels up from a WAV: build a probe path.
                if song_key(ctrl_dir / "probe.wav") in test_songs:
                    continue

                out_song = dst / singer_dir.name / tech_dir.name / song_dir.name
                if not args.dry_run:
                    out_song.mkdir(parents=True, exist_ok=True)

                # Symlink / copy static groups
                for grp in ("Control_Group", "Paired_Speech_Group"):
                    src_grp = song_dir / grp
                    dst_grp = out_song / grp
                    if src_grp.exists():
                        _link_or_copy(src_grp, dst_grp, args.copy, args.dry_run)

                if not legacy:
                    # Data-driven engines: the worker picks the group per clip.
                    for ctrl_wav in sorted(ctrl_dir.glob("*.wav")):
                        tasks.append((str(ctrl_wav), str(out_song), tech_dir.name,
                                      args.engine, args.param_mode, gamma, targets,
                                      args.language, args.dry_run))
                    continue

                # Create technique output dir
                out_tech = out_song / cfg["group_name"]
                if not args.dry_run:
                    out_tech.mkdir(exist_ok=True)

                for ctrl_wav in sorted(ctrl_dir.glob("*.wav")):
                    tasks.append((
                        str(ctrl_wav),
                        str(out_tech),
                        tech_dir.name,
                        args.dry_run,
                        args.language,
                    ))

    n_tasks = len(tasks)
    log.info("Total control utterances to process: %d", n_tasks)
    if n_tasks == 0:
        log.warning("Nothing to do — check --src path and --techniques filter.")
        return

    # ── Run augmentation ──────────────────────────────────────────────────────
    total_ok  = 0
    total_err = 0
    manifest: list[dict] = []
    worker = _process_utterance if legacy else _process_utterance_v2

    def _collect(result):
        nonlocal total_ok, total_err
        n_ok, n_err, msgs = result[:3]
        if len(result) > 3:
            manifest.extend(result[3])
        total_ok  += n_ok
        total_err += n_err
        for m in msgs:
            (log.info if m.startswith("[DRY]") else log.warning)(m)

    if args.workers > 1:
        with ProcessPoolExecutor(max_workers=args.workers) as ex:
            futures = {ex.submit(worker, t): t for t in tasks}
            for fut in tqdm(as_completed(futures), total=n_tasks, desc="augmenting"):
                _collect(fut.result())
    else:
        for task in tqdm(tasks, desc="augmenting"):
            _collect(worker(task))
    if not args.dry_run:
        write_manifest(dst, manifest)

    log.info("Done. Variants written: %d | Errors: %d", total_ok, total_err)
    if total_err:
        log.warning("%d errors — check log above for details.", total_err)


if __name__ == "__main__":
    main()
